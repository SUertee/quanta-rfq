import {chatCorrectionTools} from '../server/chat-correction.mjs';
import assert from 'node:assert/strict';
import initSqlJs from 'sql.js';
import {initIntake,createIntakeService,seedPrices,rows} from '../server/intake.mjs';
import {createResourceCorrectionStore} from '../server/resource-correction.mjs';
import {evaluateResource,businessToday} from '../shared/rfq-rules.mjs';
const SQL=await initSqlJs();
const db=new SQL.Database();
db.run('CREATE TABLE inventory(partNumber TEXT PRIMARY KEY,uom TEXT,stockQty REAL,lastPurchasePrice REAL,currency TEXT,stockCondition TEXT)');
initIntake(db);
seedPrices(db,[{id:'source-qa',partNumber:'AN3-5A',supplierName:'QA Supplier',unitPrice:20,currency:'USD',moq:100,condition:'FN',leadDays:2}]);
let failWrite=false;
const persist=()=>{if(failWrite)throw new Error('disk failed');};
const intake=createIntakeService(db,persist,{});
const inquiry=await intake.create({source:'paste',requestId:crypto.randomUUID(),operator:'QA',files:[{name:'inquiry.csv',base64:Buffer.from('件号,数量,单位,件状\nAN3-5A,10,EA,FN').toString('base64')}]});
db.run('ALTER TABLE price_resource ADD COLUMN account_id TEXT');
db.run("UPDATE price_resource SET account_id='owner-qa'");
for(const column of ['inquiry_id','account_id'])db.run(`ALTER TABLE review_log ADD COLUMN ${column} TEXT`);
const corrections=createResourceCorrectionStore(db,persist,intake);
const ctx={role:'master',accountId:'owner-qa',name:'QA'};
let evidence=intake.detail(inquiry.id).lines[0].evidence[0];
const initial=corrections.read(inquiry.id,evidence.id,ctx);
const values={...initial.resource,currency:'CNY',uom:'EA',validFrom:businessToday(),validUntil:'2099-12-31',taxBasis:'exclusive',authorized:true};
assert.throws(()=>corrections.save(inquiry.id,evidence.id,{version:'stale',values,confirmed:true,reason:'QA'},ctx),/已被修改/);
assert.throws(()=>corrections.save(inquiry.id,evidence.id,{version:initial.version,values,confirmed:false,reason:'QA'},ctx),/确认/);
assert.throws(()=>corrections.read(inquiry.id,evidence.id,{role:'sub',accountId:'other'}),/无权/);
assert.throws(()=>corrections.save(inquiry.id,evidence.id,{version:initial.version,values:{...values,unitPrice:-1},confirmed:true,reason:'QA'},ctx),/零或正数/);
failWrite=true;
assert.throws(()=>corrections.save(inquiry.id,evidence.id,{version:initial.version,values,confirmed:true,reason:'QA'},ctx),/disk failed/);
assert.equal(corrections.read(inquiry.id,evidence.id,ctx).version,initial.version,'failed persistence restores source version');
assert.equal(rows(db,'SELECT * FROM review_log').length,0);
failWrite=false;
corrections.save(inquiry.id,evidence.id,{version:initial.version,values,confirmed:true,reason:'QA 原始报价补全'},ctx);
let detail=intake.refresh(inquiry.id);
evidence=detail.lines[0].evidence[0];
let match=evaluateResource(detail.lines[0],evidence.snapshot,{source:'supplier_price'});
assert.ok(match.checks.some(check=>check.code==='moq'&&check.state==='conflict'),'completing metadata cannot override actual MOQ conflict');
const current=corrections.read(inquiry.id,evidence.id,ctx);
corrections.save(inquiry.id,evidence.id,{version:current.version,values:{...current.resource,moq:10},confirmed:true,reason:'QA 供应商确认本次起订量降至10'},ctx);
detail=intake.refresh(inquiry.id);
match=evaluateResource(detail.lines[0],detail.lines[0].evidence[0].snapshot,{source:'supplier_price'});
assert.equal(match.state,'usable','verified conditions become usable after rematching');
const log=rows(db,"SELECT * FROM review_log WHERE action='修正供应商报价'");
assert.equal(log.length,2);
assert.equal(JSON.parse(log[1].detail).before.moq,100);
assert.equal(JSON.parse(log[1].detail).after.moq,10);
assert.ok(rows(db,'SELECT * FROM evidence_history').length>0,'prior evidence remains available');
console.log('PASS: source correction, scoped ownership, stale version rejection, audit, persistence rollback, real MOQ blocking, rematch and archived evidence');
const helper=chatCorrectionTools([{inquiryId:inquiry.id,evidenceId:detail.lines[0].evidence[0].id,label:'QA Supplier'}],corrections,ctx,()=>{});
const tool=helper.tools[0];
assert.equal(JSON.parse(await tool.invoke({target:0})).resource.moq,10);
assert.equal(helper.proposal(),undefined,'reading source does not propose or save');
await tool.invoke({target:0,changes:{moq:5},reason:'QA 供应商确认最低5件'});
assert.equal(helper.proposal().differences[0].before,10);
assert.equal(helper.proposal().differences[0].after,5);
assert.equal(corrections.read(inquiry.id,detail.lines[0].evidence[0].id,ctx).resource.moq,10,'chat proposal never writes before confirmation');
assert.equal(rows(db,"SELECT * FROM review_log").length,2);
assert.match(await tool.invoke({target:9}),/请先引用/);
await assert.rejects(()=>tool.invoke({target:0,changes:{quantity:50},reason:'QA'}));
console.log('PASS: conversational source reads, typed proposal, no implicit writes, unavailable targets and inquiry quantity edits blocked');
db.close();
