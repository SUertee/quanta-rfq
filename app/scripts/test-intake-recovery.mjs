import assert from 'node:assert/strict';
import initSqlJs from 'sql.js';
import {randomUUID} from 'node:crypto';
import {createIntakeService,initIntake,rows,recoverInterruptedIntakes} from '../server/intake.mjs';
const SQL=await initSqlJs();
let db=new SQL.Database(),disk,failure=false;
db.run('CREATE TABLE inventory(partNumber TEXT PRIMARY KEY,uom TEXT,stockQty REAL,lastPurchasePrice REAL,currency TEXT,stockCondition TEXT)');
db.run("INSERT INTO inventory VALUES('AN3-5A','EA',100,14.37,'CNY','FN'),('TEST-2','EA',100,20,'CNY','FN')");
initIntake(db);
const persist=()=>{if(failure)throw Error('QA disk error');disk=db.export();};
const originals=['PN,Quantity,Unit,Condition\nAN3-5A,10,EA,FN','PN,Quantity,Unit,Condition\nTEST-2,20,EA,FN'];
const input={requestId:randomUUID(),files:originals.map((text,index)=>({name:`original-${index}.csv`,base64:Buffer.from(text).toString('base64')}))};
const service=createIntakeService(db,persist,{semantic:async()=>({lines:[],issues:[]})});
await assert.rejects(service.create(input,stage=>{if(stage===1)throw Error('QA process exits after acceptance');}),/process exits/);
let batch=service.detail(service.list()[0].id);
assert.equal(batch.status,'processing');assert.equal(batch.files.length,2);assert.equal(batch.lines.length,0);
assert.deepEqual(batch.files.map(file=>Buffer.from(service.rawFile(file.id).raw).toString()),originals);
const originalIds=batch.files.map(file=>file.id);
db.close();db=new SQL.Database(disk);initIntake(db);
recoverInterruptedIntakes(db);
let calls=0,release;
const barrier=new Promise(resolve=>{release=resolve;});
const recoveredService=createIntakeService(db,persist,{semantic:async()=>{calls++;await barrier;return {lines:[],issues:[]};}});
batch=recoveredService.detail(batch.id);
const check=recoveredService.recovery(batch.id);assert.equal(check.canRecover,true);
const body={requestId:randomUUID(),fingerprint:check.fingerprint,operator:'QA'};
await assert.rejects(recoveredService.recover(batch.id,{...body,fingerprint:'stale'}),error=>error.status===409);
await assert.rejects(recoveredService.recover(batch.id,null),error=>error.status===400);
const before=()=>({inquiry:rows(db,'SELECT * FROM inquiry'),logs:rows(db,'SELECT * FROM review_log')});
const saved=before();failure=true;
await assert.rejects(recoveredService.recover(batch.id,body),/disk error/);assert.deepEqual(before(),saved);failure=false;
const active=recoveredService.recover(batch.id,body);await new Promise(resolve=>setImmediate(resolve));
assert.equal(calls,1);
assert.equal((await recoveredService.recover(batch.id,body)).status,'processing');
await assert.rejects(recoveredService.recover(batch.id,{...body,requestId:randomUUID()}),error=>error.status===409);
assert.throws(()=>recoveredService.addLine(batch.id,{partNumber:'OTHER',quantity:1,uom:'EA'}),error=>error.status===409);
assert.throws(()=>recoveredService.refresh(batch.id),error=>error.status===409);
release();const complete=await active;
assert.equal(complete.status,'evidence_ready');assert.equal(complete.lines.length,2);assert.deepEqual(complete.files.map(file=>file.id),originalIds);
assert.equal((await recoveredService.recover(batch.id,body)).lines.length,2);assert.equal(calls,1);
assert.equal(rows(db,"SELECT * FROM review_log WHERE action='恢复材料处理'").length,1);
const changed=recoveredService.updateLine(batch.id,complete.lines[0].id,{version:1,patch:{quantity:99},operator:'QA'});
recoveredService.addLine(batch.id,{partNumber:'MANUAL-3',quantity:1,uom:'EA',operator:'QA'});
const manual=recoveredService.detail(batch.id);const versions=manual.lines.map(line=>({id:line.id,version:line.version,quantity:line.quantity,issues:line.issues}));
db.run("UPDATE inquiry SET status='interrupted',issues='[\"服务重启中断了处理，已保留已接收文件\"]' WHERE id=?",[batch.id]);
const savedLineCheck=recoveredService.recovery(batch.id);
const resumed=await recoveredService.recover(batch.id,{requestId:randomUUID(),fingerprint:savedLineCheck.fingerprint,operator:'QA'});
assert.deepEqual(resumed.lines.map(line=>({id:line.id,version:line.version,quantity:line.quantity,issues:line.issues})),versions);
assert.equal(calls,1);assert.equal(resumed.status,'needs_input');assert.equal(changed.lines[0].quantity,99);
assert.equal(JSON.parse(rows(db,"SELECT detail FROM review_log WHERE action='恢复材料处理' ORDER BY id DESC")[0].detail).mode,'resume_saved_lines');
// Recovery must refuse a legacy interrupted upload whose later original never reached disk.
const truncated=await recoveredService.create({...input,requestId:randomUUID()},stage=>{if(stage===1)throw Error('QA incomplete manifest');}).catch(()=>recoveredService.list()[0]);
db.run("UPDATE inquiry SET status='interrupted' WHERE id=?",[truncated.id]);
const last=rows(db,'SELECT id FROM file WHERE inquiry_id=? ORDER BY rowid DESC',[truncated.id])[0];db.run('DELETE FROM file WHERE id=?',[last.id]);
assert.equal(recoveredService.recovery(truncated.id).canRecover,false);
// An email retry reuses attachment IDs and content IDs instead of appending duplicates.
const eml=['From: buyer@example.test','To: quote@example.test','Subject: Recovery email','MIME-Version: 1.0','Content-Type: multipart/mixed; boundary="qa"','','--qa','Content-Type: text/plain','','Please quote attached parts.','--qa','Content-Type: text/csv; name="parts.csv"','Content-Disposition: attachment; filename="parts.csv"','','PN,Quantity,Unit,Condition','AN3-5A,10,EA,FN','--qa--',''].join('\r\n');
const simple=createIntakeService(db,persist,{semantic:async()=>({lines:[],issues:[]})});
const email=await simple.create({requestId:randomUUID(),files:[{name:'original.eml',mime:'message/rfc822',base64:Buffer.from(eml).toString('base64')}]},stage=>{if(stage===2)throw Error('QA interrupted before extraction');});
assert.equal(email.status,'failed');assert.equal(email.lines.length,0);
const emailCheck=simple.recovery(email.id);assert.equal(emailCheck.canRecover,true);
const retriedEmail=await simple.recover(email.id,{requestId:randomUUID(),fingerprint:emailCheck.fingerprint,operator:'QA'});
assert.deepEqual(retriedEmail.files.map(file=>file.id),email.files.map(file=>file.id));
assert.deepEqual(retriedEmail.contents.map(content=>content.id),email.contents.map(content=>content.id));
assert.equal(retriedEmail.lines.length,1);
const checkpoint=await simple.create({...input,requestId:randomUUID()},stage=>{if(stage===3)throw Error('QA failure after saved lines');});
assert.equal(checkpoint.status,'failed');assert.equal(checkpoint.lines.length,2);
const checkpointCheck=simple.recovery(checkpoint.id);
const checkpointRetry=await simple.recover(checkpoint.id,{requestId:randomUUID(),fingerprint:checkpointCheck.fingerprint,operator:'QA'});
assert.equal(checkpointRetry.status,'evidence_ready');assert.equal(checkpointRetry.lines.length,2);
db.run("UPDATE inquiry SET status='interrupted' WHERE id=?",[checkpointRetry.id]);
let writes=0;
const brokenDisk=createIntakeService(db,()=>{if(++writes>1)throw Error('QA final disk failure');persist();});
const diskCheck=brokenDisk.recovery(checkpointRetry.id);
const diskResult=await brokenDisk.recover(checkpointRetry.id,{requestId:randomUUID(),fingerprint:diskCheck.fingerprint,operator:'QA'});
assert.equal(diskResult.status,'failed');assert.ok(diskResult.issues.some(issue=>issue.includes('final disk failure')));
const warnings=['原文包含尚未落实的要求'];
db.run("UPDATE inquiry SET status='processing',issues=? WHERE id=?",[JSON.stringify(warnings),retriedEmail.id]);
recoverInterruptedIntakes(db);
const warningCheck=simple.recovery(retriedEmail.id);
const warningResult=await simple.recover(retriedEmail.id,{requestId:randomUUID(),fingerprint:warningCheck.fingerprint,operator:'QA'});
assert.deepEqual(warningResult.issues,warnings);assert.equal(warningResult.status,'needs_input');
const duplicateEmail=eml.replace('--qa--','--qa\r\nContent-Type: text/csv; name="parts.csv"\r\nContent-Disposition: attachment; filename="parts.csv"\r\n\r\nPN,Quantity,Unit,Condition\r\nAN3-5A,10,EA,FN\r\n--qa--');
const duplicates=await simple.create({requestId:randomUUID(),files:[{name:'duplicates.eml',base64:Buffer.from(duplicateEmail).toString('base64')}]},stage=>{if(stage===2)throw Error('QA duplicate checkpoint');});
assert.equal(duplicates.files.length,3);assert.equal(new Set(duplicates.files.map(file=>file.id)).size,3);
const duplicateCheck=simple.recovery(duplicates.id);
const duplicateRetry=await simple.recover(duplicates.id,{requestId:randomUUID(),fingerprint:duplicateCheck.fingerprint,operator:'QA'});
assert.deepEqual(duplicateRetry.files.map(file=>file.id),duplicates.files.map(file=>file.id));
assert.equal(new Set(duplicateRetry.contents.map(content=>content.id)).size,duplicateRetry.contents.length);
// The HTTP background mode returns promptly while parsing continues, so polling can reconnect.
let finish;const waiting=new Promise(resolve=>{finish=resolve;});
const slow=createIntakeService(db,persist,{semantic:async()=>{await waiting;return {lines:[],issues:[]};}});
const pending=await simple.create({...input,requestId:randomUUID()},stage=>{if(stage===1)throw Error('QA detached recovery');}).catch(()=>simple.list()[0]);
recoverInterruptedIntakes(db);
const pendingCheck=slow.recovery(pending.id);
const pendingBody={requestId:randomUUID(),fingerprint:pendingCheck.fingerprint,operator:'QA'};
assert.equal((await slow.recover(pending.id,pendingBody,{background:true})).status,'processing');
finish();
for(let retry=0;retry<100&&slow.detail(pending.id).status==='processing';retry++)await new Promise(resolve=>setTimeout(resolve,5));
assert.equal(slow.detail(pending.id).status,'evidence_ready');
const reload=new SQL.Database(disk);assert.ok(rows(reload,"SELECT * FROM review_log WHERE action='恢复材料处理'").length>=3);reload.close();db.close();
console.log('PASS: all originals persisted before parsing, restart recovery, original/content identity, stable request retry, concurrent recovery and edit guards, disk rollback, manual revisions, incomplete manifest refusal, email attachment reuse and durable recovery audit');
